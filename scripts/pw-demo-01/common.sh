#!/usr/bin/env bash
set -euo pipefail

DEMO_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE_ROOT="$(cd "$DEMO_SCRIPT_DIR/../.." && pwd)"
RUNTIME_ROOT="$WORKSPACE_ROOT/.local-networks/pw-demo-01"
CLI_HOME="$RUNTIME_ROOT/cli-home"
CONFIG_DIR="$RUNTIME_ROOT/config"
LOCAL_DATA_DIR="$RUNTIME_ROOT/data"
PRIVATE_DIR="$RUNTIME_ROOT/private"
METADATA_DIR="$RUNTIME_ROOT/metadata"
PID_DIR="$RUNTIME_ROOT/pids"
LOG_DIR="$RUNTIME_ROOT/logs"

export HOME="$CLI_HOME"
export LOCAL_BIN_DIR="$WORKSPACE_ROOT/local-bin"
export CHAIN_DIR="$CONFIG_DIR"
export CONFIG_DIR
export LOCAL_DATA_DIR

source "$WORKSPACE_ROOT/scripts/_common.sh"

DEMO_READY_FILE="$METADATA_DIR/ready"
DEMO_ATTEMPT_FILE="$METADATA_DIR/initialization-started"
DEMO_ACCOUNTS_FILE="$METADATA_DIR/accounts.json"
DEMO_TRANSFER_FILE="$METADATA_DIR/transfer.json"
DEMO_TRANSFER_ATTEMPT_FILE="$METADATA_DIR/transfer-attempted"
DEMO_KEY_FILE="$PRIVATE_DIR/sender.key"

demo_error() {
    printf '[pw-demo-01] ERROR: %s\n' "$*" >&2
}

ensure_demo_dirs() {
    [[ ! -L "$RUNTIME_ROOT" ]] || {
        demo_error "Runtime root must not be a symlink."
        return 1
    }
    mkdir -p "$RUNTIME_ROOT" "$CLI_HOME" "$CONFIG_DIR/genesis" \
        "$LOCAL_DATA_DIR" "$PRIVATE_DIR" "$METADATA_DIR" "$PID_DIR" "$LOG_DIR"
    chmod 700 "$RUNTIME_ROOT" "$CLI_HOME" "$CONFIG_DIR" \
        "$CONFIG_DIR/genesis" "$LOCAL_DATA_DIR" "$PRIVATE_DIR" \
        "$METADATA_DIR" "$PID_DIR" "$LOG_DIR"
    assert_demo_paths_isolated
}

assert_demo_paths_isolated() {
    local root resolved path
    root="$(realpath -m "$RUNTIME_ROOT")"
    for path in "$CLI_HOME" "$CONFIG_DIR" "$LOCAL_DATA_DIR" "$PRIVATE_DIR" \
        "$METADATA_DIR" "$PID_DIR" "$LOG_DIR"; do
        resolved="$(realpath -m "$path")"
        [[ "$resolved" == "$root"/* ]] || {
            demo_error "Writable path escapes the isolated runtime: $path"
            return 1
        }
        [[ "$resolved" != "$WORKSPACE_ROOT/local-data"* ]] || {
            demo_error "Historical local-data path is forbidden."
            return 1
        }
        [[ "$resolved" != "$WORKSPACE_ROOT/recovery-backups"* ]] || {
            demo_error "Recovery-backups path is forbidden."
            return 1
        }
    done
}

read_demo_state() {
    local state="$LOCAL_DATA_DIR/network-state.env"
    [[ -f "$state" ]] || {
        demo_error "No verified demonstration network state exists."
        return 1
    }
    # This file is generated by scripts/start-local.sh and contains identifiers
    # and loopback URLs only; it contains no credentials or private keys.
    # shellcheck source=/dev/null
    source "$state"
    [[ "${PRIMEWAVE_DEV_CHAIN_ID:-}" == "73571" ]] || {
        demo_error "Saved runtime is not Chain ID 73571."
        return 1
    }
    [[ "${PRIMEWAVE_BLOCKCHAIN_ID:-}" =~ ^[A-Za-z0-9]+$ ]] || {
        demo_error "Saved Blockchain ID is invalid."
        return 1
    }
    [[ "${PRIMEWAVE_SUBNET_ID:-}" =~ ^[A-Za-z0-9]+$ ]] || {
        demo_error "Saved Subnet ID is invalid."
        return 1
    }
}

demo_node_dir() {
    printf '%s\n' "$HOME/.avalanche-cli/local/primewavedev-local-node-local-network"
}
