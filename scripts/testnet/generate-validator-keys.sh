#!/usr/bin/env bash
# ============================================================
# PrimeWave Testnet — Validator Key Generation Procedure
# Sprint PW-C14 | TESTNET ONLY
# ============================================================
# Documents and automates the testnet validator key generation.
#
# IMPORTANT SECURITY NOTES:
#   - Testnet keys: software generation is acceptable (cast wallet new)
#   - Mainnet keys: hardware wallet REQUIRED (see PRIMEWAVE_KEY_SECURITY_PROCEDURE.md)
#   - Never commit private keys to Git
#   - Never log private keys
#   - Store private keys in encrypted form only (e.g., age-encrypted)
#
# Generates:
#   1. Keeper signer key (EOA)
#   2. Testnet deployer key (EOA)
#   3. Testnet EMS signer keys (5 × EOA)
#   4. Node keys are generated by avalanchego at node startup — NOT here
#
# Usage:
#   TESTNET_KEY_DIR=/secure/testnet-keys bash scripts/testnet/generate-validator-keys.sh
# ============================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

export PATH="$REPO_ROOT/local-bin/foundry:$REPO_ROOT/local-bin:$PATH"

KEY_DIR="${TESTNET_KEY_DIR:-/tmp/pw-testnet-keys}"
mkdir -p "$KEY_DIR"
chmod 700 "$KEY_DIR"

echo ""
echo "══ PrimeWave Testnet — Key Generation ══"
echo "  ENVIRONMENT: TESTNET ONLY"
echo "  Output:      $KEY_DIR"
echo "  WARNING:     NEVER use these keys on mainnet."
echo "  WARNING:     NEVER commit private keys to Git."
echo ""

generate_key() {
  local label="$1"
  local outfile="$KEY_DIR/${label}.json"
  if [[ -f "$outfile" ]]; then
    echo "[SKIP]  $label already exists: $outfile"
    return
  fi
  echo "[GEN]   Generating key: $label ..."
  cast wallet new --json > "$outfile" 2>/dev/null
  chmod 600 "$outfile"
  local addr
  addr=$(python3 -c "import json,sys; d=json.load(open('$outfile')); print(d[0]['address'] if isinstance(d,list) else d['address'])")
  echo "[OK]    $label => $addr"
  echo "        Key stored (private): $outfile"
}

# Generate testnet EOA keys
generate_key "testnet-deployer"
generate_key "testnet-keeper-signer"
generate_key "testnet-ems-signer-1"
generate_key "testnet-ems-signer-2"
generate_key "testnet-ems-signer-3"
generate_key "testnet-ems-signer-4"
generate_key "testnet-ems-signer-5"

echo ""
echo "══ Key Summary (PUBLIC addresses only) ══"
for f in "$KEY_DIR"/*.json; do
  label=$(basename "$f" .json)
  addr=$(python3 -c "import json; d=json.load(open('$f')); print(d[0]['address'] if isinstance(d,list) else d['address'])" 2>/dev/null || echo "ERROR")
  echo "  $label => $addr"
done

echo ""
echo "══ Node Keys ══"
echo "  Node keys (NodeID + BLS) are generated by AvalancheGo at node startup."
echo "  On each validator node, run:"
echo "    avalanchego --version  # Verify v1.15.0-fuji"
echo "    # Start node — NodeID and BLS key generated automatically"
echo "    # Find NodeID in node logs: 'My NodeID is NodeID-...'"
echo "    # BLS public key: curl -s http://localhost:9650/ext/info | jq .publicKey"
echo ""
echo "  Record each validator's NodeID and BLS public key in:"
echo "    docs/PW-C14-TESTNET-DEPLOYMENT-MANIFEST.md"
echo ""
echo "[DONE]  Key generation complete."
echo "        Encrypt and back up all files in $KEY_DIR before proceeding."
